import type { Hero, HeroStats } from '../state/types';
import { t } from '../i18n';

const KING_NAMES = [
  'Lý Thánh Tông',
  'Trần Nhân Tông',
  'Lê Thái Tổ',
  'Đinh Bộ Lĩnh',
  'Ngô Quyền',
  'Quang Trung',
];

const KING_TRAITS: Array<{
  effectKey: 'heroes.king.trait_morale.effect' | 'heroes.king.trait_power.effect' | 'heroes.king.trait_rations.effect';
  upkeepGold: number }
> = [
  { effectKey: 'heroes.king.trait_morale.effect', upkeepGold: 12 },
  { effectKey: 'heroes.king.trait_power.effect', upkeepGold: 14 },
  { effectKey: 'heroes.king.trait_rations.effect', upkeepGold: 10 },
];

const KING_STATS: HeroStats = {
  martial: 78,
  logistics: 50,
  administration: 40,
  diplomacy: 45,
  loyalty: 55,
  renown: 75,
};

/** Generates the player's starting commander - a randomized King, not part of the hero draft deck. */
export function generateKingHero(): Hero {
  const name = KING_NAMES[Math.floor(Math.random() * KING_NAMES.length)];
  const trait = KING_TRAITS[Math.floor(Math.random() * KING_TRAITS.length)];

  return {
    id: 'king',
    name,
    type: 'general',
    rarity: 'Legendary',
    upkeepGold: trait.upkeepGold,
    description: t('heroes.king.description'),
    effect: t(trait.effectKey),
    stats: { ...KING_STATS },
    fatigue: 0,
  };
}

