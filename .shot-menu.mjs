import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 900, height: 1000 }, deviceScaleFactor: 3 });
await page.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__phaserGame?.scene.isActive('MenuScene'), null, { timeout: 25000 });
await page.waitForTimeout(1600);
const c = await page.evaluate(() => { const r = window.__phaserGame.canvas.getBoundingClientRect(); return { l: r.left, w: r.width }; });
await page.screenshot({ path: process.argv[2], clip: { x: c.l, y: 190, width: c.w, height: 190 } });
console.log('ok');
await browser.close();
